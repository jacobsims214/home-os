/*
 * The viewport, and the theme-colour metas.
 *
 * viewport-fit=cover is what makes env(safe-area-inset-*) non-zero. The shell
 * already pads the header top and the tab bar bottom with them
 * (components/shared/DashboardShell.tsx, the approved spec's "Safe areas"
 * section), so without it the iPhone would letterbox the app and the insets
 * would collapse to 0.
 *
 * No maximum-scale and no user-scalable=no: both stop the double-tap zoom but
 * also pinch zoom, which fails WCAG 1.4.4. The double-tap zoom is stopped in
 * globals.css with `touch-action: manipulation` instead, which keeps pinch.
 *
 * themeColor: the manifest's colour is static, so the browser chrome gets one
 * meta per scheme. These are --surface, because every page's top edge is the
 * shell header, which sits on --surface in both schemes.
 */
export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  viewportFit: "cover",
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: "#ffffff" }, // --surface, light
    { media: "(prefers-color-scheme: dark)", color: "#242424" }, // --surface, dark
  ],
};

